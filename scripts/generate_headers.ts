// Paths
const ROOT_DIR = path.resolve(".");
const INCLUDE_DIR = path.join(ROOT_DIR, "include");
const PUBLIC_WASM_DIR = path.join(ROOT_DIR, "public", "wasm");
const WASM_EMBED_TS = path.join(ROOT_DIR, "src", "wasm", "sample_app_wasm.ts");
const CONSTANTS_TS = path.join(ROOT_DIR, "src", "win32", "constants.ts");
const RC_CONSTANTS_TS = path.join(ROOT_DIR, "src", "rc", "constants.ts");

interface ConstantItem {
  name: string;
  value: string;
  category?: string;
  comment?: string;
}

// Read and extract constants from constants.ts and rc/constants.ts
function extractConstants(): Map<string, ConstantItem> {
  const constants = new Map<string, ConstantItem>();

  const constantsContent = fs.readFileSync(CONSTANTS_TS, "utf-8");
  const lines = constantsContent.split("\n");
  let currentCategory = "General";

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line.startsWith("//") && !line.startsWith("///")) {
      const commentText = line.replace(/^\/\/\s*=*\s*/, "").replace(/\s*=*\s*$/, "").trim();
      if (commentText.length > 0 && !commentText.startsWith("Helpers")) {
        currentCategory = commentText;
      }
      continue;
    }

    const match = line.match(/^export\s+const\s+([A-Za-z0-9_]+)\s*=\s*(.+?)$/);
    if (match) {
      const name = match[1];
      let value = match[2].trim();

      // Normalize multi-line expressions like WS_OVERLAPPEDWINDOW
      if (value.startsWith("(") && !value.includes(");") && !value.endsWith(")")) {
        let multiline = value;
        while (i + 1 < lines.length && !lines[i + 1].trim().endsWith(");") && !lines[i + 1].trim().endsWith(")")) {
          i++;
          multiline += " " + lines[i].trim();
        }
        if (i + 1 < lines.length) {
          i++;
          multiline += " " + lines[i].trim();
        }
        value = multiline;
      }

      // Strip inline comments & trailing semicolons
      value = value.replace(/\/\/.*$/, "").trim().replace(/;+$/, "").trim();

      // Don't emit constants that are string class names (keep numeric / macro defines)
      if (value.startsWith('"') && !name.endsWith("CLASS") && !name.endsWith("NAME") && !name.startsWith("WC_")) {
        continue;
      }

      constants.set(name, {
        name,
        value,
        category: currentCategory,
      });
    }
  }

  // Also check rc/constants.ts for DS_* or control styles
  if (fs.existsSync(RC_CONSTANTS_TS)) {
    const rcContent = fs.readFileSync(RC_CONSTANTS_TS, "utf-8");
    const rcMatches = rcContent.matchAll(/([A-Za-z0-9_]+):\s*(0x[0-9a-fA-F]+|[0-9\-]+|[A-Za-z0-9_| ]+),/g);
    for (const m of rcMatches) {
      const name = m[1];
      const val = m[2].trim();
      if (!constants.has(name) && !name.startsWith("ID_")) {
        constants.set(name, {
          name,
          value: val,
          category: "Resource Constants",
        });
      }
    }
  }

  return constants;
}

