// Main execution
function main() {
  console.log("=== Win32 Header Generator (Node 24 / ESM) ===");

  if (!fs.existsSync(INCLUDE_DIR)) {
    fs.mkdirSync(INCLUDE_DIR, { recursive: true });
  }
  if (!fs.existsSync(PUBLIC_WASM_DIR)) {
    fs.mkdirSync(PUBLIC_WASM_DIR, { recursive: true });
  }

  // 1. Extract constants
  console.log("Extracting constants from src/win32/constants.ts and src/rc/constants.ts...");
  const allConstants = extractConstants();
  console.log(`Extracted ${allConstants.size} Win32 constants.`);

  // 2. Generate header contents
  const headerMap = new Map<string, string>();
  headerMap.set("windef.h", generateWindefH());
  headerMap.set("winbase.h", generateWinbaseH(allConstants));
  headerMap.set("wingdi.h", generateWingdiH(allConstants));
  headerMap.set("winuser.h", generateWinuserH(allConstants));
  headerMap.set("commctrl.h", generateCommctrlH(allConstants));
  headerMap.set("shellapi.h", generateShellapiH(allConstants));
  headerMap.set("winspool.h", generateWinspoolH(allConstants));
  headerMap.set("sql.h", generateSqlH(allConstants));
  headerMap.set("windows.h", generateWindowsH());

  // 3. Write modular headers to include/
  for (const [filename, content] of headerMap.entries()) {
    const targetPath = path.join(INCLUDE_DIR, filename);
    fs.writeFileSync(targetPath, content, "utf-8");
    console.log(`  ✓ Wrote include/${filename}`);
  }

  // 4. Generate amalgamated single header
  const amalgamated = generateAmalgamatedWindowsH(headerMap);
  fs.writeFileSync(path.join(INCLUDE_DIR, "windows-all.h"), amalgamated, "utf-8");
  fs.writeFileSync(path.join(PUBLIC_WASM_DIR, "windows.h"), amalgamated, "utf-8");
  console.log("  ✓ Wrote public/wasm/windows.h (amalgamated)");

  // 5. Copy all modular headers to public/wasm/ for direct HTTP downloads
  for (const [filename, content] of headerMap.entries()) {
    fs.writeFileSync(path.join(PUBLIC_WASM_DIR, filename), content, "utf-8");
  }
  console.log("  ✓ Synchronized all modular headers to public/wasm/");

  // 6. Update src/wasm/sample_app_wasm.ts
  if (fs.existsSync(WASM_EMBED_TS)) {
    let embedContent = fs.readFileSync(WASM_EMBED_TS, "utf-8");

    // Replace exported header sources
    const replaceExport = (varName: string, source: string) => {
      const regex = new RegExp(`^export const ${varName} = .*;$`, "m");
      const replacement = `export const ${varName} = ${JSON.stringify(source)};`;
      if (regex.test(embedContent)) {
        embedContent = embedContent.replace(regex, replacement);
      } else {
        embedContent += replacement + "\n";
      }
    };

    replaceExport("WINDOWS_H_SOURCE", headerMap.get("windows.h")!);
    replaceExport("WINDEF_H_SOURCE", headerMap.get("windef.h")!);
    replaceExport("WINUSER_H_SOURCE", headerMap.get("winuser.h")!);
    replaceExport("WINGDI_H_SOURCE", headerMap.get("wingdi.h")!);
    replaceExport("WINBASE_H_SOURCE", headerMap.get("winbase.h")!);
    replaceExport("COMMCTRL_H_SOURCE", headerMap.get("commctrl.h")!);
    replaceExport("SHELLAPI_H_SOURCE", headerMap.get("shellapi.h")!);
    replaceExport("WINSPOOL_H_SOURCE", headerMap.get("winspool.h")!);
    replaceExport("SQL_H_SOURCE", headerMap.get("sql.h")!);

    fs.writeFileSync(WASM_EMBED_TS, embedContent, "utf-8");
    console.log("  ✓ Updated src/wasm/sample_app_wasm.ts with new header sources");
  }

  // 7. Package archives (tar.gz and zip)
  try {
    const tarPath = path.join(PUBLIC_WASM_DIR, "win32-wasm-headers.tar.gz");
    const zipPath = path.join(PUBLIC_WASM_DIR, "win32-wasm-headers.zip");

    execSync(`tar -czf "${tarPath}" -C "${INCLUDE_DIR}" .`, { stdio: "ignore" });
    console.log(`  ✓ Packaged ${tarPath}`);

    execSync(`cd "${INCLUDE_DIR}" && zip -q -r "${zipPath}" .`, { stdio: "ignore" });
    console.log(`  ✓ Packaged ${zipPath}`);
  } catch (err: any) {
    console.warn("  ⚠ Warning: Archive packaging skipped or failed:", err?.message || err);
  }

  console.log("=== Win32 Header Generation Complete ===");
}

main();
