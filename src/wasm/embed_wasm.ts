import * as fs from "fs";
import * as path from "path";

const wasmPath = path.resolve("src/wasm/sample_app.wasm");
const cSourcePath = path.resolve("src/wasm/sample_app.c");
const windowsHPath = path.resolve("include/windows.h");
const windefHPath = path.resolve("include/windef.h");
const winuserHPath = path.resolve("include/winuser.h");
const wingdiHPath = path.resolve("include/wingdi.h");
const winbaseHPath = path.resolve("include/winbase.h");

const outTsPath = path.resolve("src/wasm/sample_app_wasm.ts");
const publicDir = path.resolve("public/wasm");
const publicWasmPath = path.join(publicDir, "sample_app.wasm");

if (!fs.existsSync(wasmPath)) {
  console.error("sample_app.wasm not found at", wasmPath);
  process.exit(1);
}

const wasmBuffer = fs.readFileSync(wasmPath);
const base64 = wasmBuffer.toString("base64");

const cSource = fs.readFileSync(cSourcePath, "utf-8");
const windowsH = fs.readFileSync(windowsHPath, "utf-8");
const windefH = fs.readFileSync(windefHPath, "utf-8");
const winuserH = fs.readFileSync(winuserHPath, "utf-8");
const wingdiH = fs.readFileSync(wingdiHPath, "utf-8");
const winbaseH = fs.readFileSync(winbaseHPath, "utf-8");

const tsContent = `// Auto-generated by src/wasm/embed_wasm.ts - DO NOT EDIT MANUALLY
export const SAMPLE_APP_WASM_BASE64 = "${base64}";

export function getSampleAppWasmBytes(): Uint8Array {
  const binaryString = atob(SAMPLE_APP_WASM_BASE64);
  const bytes = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes;
}

export const SAMPLE_APP_C_SOURCE = ${JSON.stringify(cSource)};
export const WINDOWS_H_SOURCE = ${JSON.stringify(windowsH)};
export const WINDEF_H_SOURCE = ${JSON.stringify(windefH)};
export const WINUSER_H_SOURCE = ${JSON.stringify(winuserH)};
export const WINGDI_H_SOURCE = ${JSON.stringify(wingdiH)};
export const WINBASE_H_SOURCE = ${JSON.stringify(winbaseH)};
`;

fs.writeFileSync(outTsPath, tsContent, "utf-8");
console.log(`Generated ${outTsPath} (${base64.length} base64 chars)`);

if (!fs.existsSync(publicDir)) {
  fs.mkdirSync(publicDir, { recursive: true });
}
fs.copyFileSync(wasmPath, publicWasmPath);
fs.copyFileSync(cSourcePath, path.join(publicDir, "sample_app.c"));
fs.copyFileSync(windowsHPath, path.join(publicDir, "windows.h"));
console.log(`Copied assets to ${publicDir}`);
